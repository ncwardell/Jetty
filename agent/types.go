// peerWire is the on-the-wire representation of a Peer for the
// /api/join response. It mirrors Peer but EXPLICITLY includes APIKey
// (which Peer's json:"-" tag suppresses everywhere else) so the joiner
// can populate its peer table with the credentials needed to call each
// peer back. Used nowhere else.
type peerWire struct {
	ID       string    `json:"id"`
	Name     string    `json:"name"`
	IP       string    `json:"ip"`
	Healthy  bool      `json:"healthy"`
	LastSeen time.Time `json:"last_seen"`
	Version  string    `json:"version"`
	Arch     string    `json:"arch"`
	APIKey   string    `json:"api_key,omitempty"`
}

func peerToWire(p *Peer) peerWire {
	return peerWire{
		ID: p.ID, Name: p.Name, IP: p.IP, Healthy: p.Healthy,
		LastSeen: p.LastSeen, Version: p.Version, Arch: p.Arch, APIKey: p.APIKey,
	}
}

func (w peerWire) toPeer() *Peer {
	return &Peer{
		ID: w.ID, Name: w.Name, IP: w.IP, Healthy: w.Healthy,
		LastSeen: w.LastSeen, Version: w.Version, Arch: w.Arch, APIKey: w.APIKey,
	}
}

